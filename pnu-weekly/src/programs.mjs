/** 제목에 언급된 사업 id 들. 한 기사가 여럿을 함께 다루기도 한다('AI중심대학·AX대학원 동시 선정'). */
export function programsOf(title) {
  const t = String(title || '');
  return PROGRAMS.filter((p) => p.re.test(t)).map((p) => p.id);
}

